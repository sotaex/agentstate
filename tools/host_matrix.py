"""0.33.0 (A2): Host verification matrix generator.

Scans three sources and emits docs/HOST_MATRIX.md:
  1. rules/hosts/*.json      -- registered watch paths (host_shield)
  2. hooks/pre_tool_use.py   -- HOST_ADAPTERS verified flags
  3. .psl/probe/*.json       -- probe evidence (per-project, optional)

Usage: python tools/host_matrix.py [--output docs/HOST_MATRIX.md]
Python 3.10+, stdlib only, no network.
"""
import io
import json
import os
import re
import sys
from datetime import datetime, timezone
from pathlib import Path

PKG = Path(__file__).resolve().parent.parent


def _load_adapters():
    """Parse HOST_ADAPTERS verified flags from pre_tool_use.py source (no import)."""
    src = (PKG / "hooks" / "pre_tool_use.py").read_text(encoding="utf-8", errors="replace")
    i = src.find("HOST_ADAPTERS")
    seg = src[i:i + 2000] if i >= 0 else ""
    out = {}
    for m in re.finditer(r'"([\w-]+)":\s*\{[^}]*"verified":\s*(True|False)', seg):
        out[m.group(1)] = m.group(2) == "True"
    return out


def _load_registry_hosts():
    d = PKG / "rules" / "hosts"
    if not d.is_dir():
        return {}
    out = {}
    for f in sorted(d.glob("*.json")):
        try:
            data = json.loads(f.read_text(encoding="utf-8"))
            out[f.stem] = {"watch_count": len(data.get("watch", [])),
                           "lock_dirs": data.get("lock_dirs", [])}
        except Exception:
            pass
    return out


def _load_probe_evidence():
    d = PKG / ".psl" / "probe"
    if not d.is_dir():
        return {}
    out = {}
    for f in sorted(d.glob("*.json")):
        try:
            data = json.loads(f.read_text(encoding="utf-8"))
            tag = data.get("tag", "?")
            out.setdefault(tag, []).append(f.name)
        except Exception:
            pass
    return out


def _load_chain_evidence():
    """0.33.1 (P4-3): 链上证据 —— host_confidence=high 的真实记录数。

    为什么必须有这一列：此前 Probe evidence 列 25 行全是「—」，因为 .psl/probe/
    里从来没有文件；矩阵里那些 ✅/❌ 是**凭记忆标的**，不是可复核的事实。

    链才是最硬的证据：一条 `host=workbuddy` + `host_confidence=high` 的
    pre_tool_use 记录，就是"这个宿主的钩子真的在跑、且归因有据"的实证。

    扫描目录：默认 <pkg>/.psl/audit，可用 ANTINEL_AUDIT_DIRS 追加（逗号分隔）。
    """
    import collections
    dirs = [str(PKG / ".psl" / "audit")]
    extra = os.environ.get("ANTINEL_AUDIT_DIRS")
    if extra:
        dirs += [d.strip() for d in extra.split(",") if d.strip()]
    counts = collections.Counter()
    last = {}
    for d in dirs:
        dd = Path(d)
        if not dd.is_dir():
            continue
        for f in sorted(dd.glob("*.jsonl")):
            try:
                for ln in f.read_text(encoding="utf-8", errors="replace").splitlines():
                    if not ln.strip():
                        continue
                    try:
                        e = json.loads(ln)
                    except Exception:
                        continue
                    if (e.get("type") in ("pre_tool_use", "post_tool_use")
                            and e.get("host_confidence") == "high"):
                        h = e.get("host") or "?"
                        counts[h] += 1
                        ts = (e.get("ts") or "")[:10]
                        if ts > last.get(h, ""):
                            last[h] = ts
            except Exception:
                pass
    return counts, last


def build_matrix():
    adapters = _load_adapters()
    registry = _load_registry_hosts()
    probes = _load_probe_evidence()
    chain, chain_last = _load_chain_evidence()
    all_hosts = sorted(set(list(adapters.keys()) + list(registry.keys())))
    now = datetime.now(timezone.utc).astimezone().strftime("%Y-%m-%d %H:%M")
    lines = [
        "# Host Verification Matrix",
        "",
        "> Auto-generated by `tools/host_matrix.py` on %s. Do not edit." % now,
        "> Source of truth: `hooks/pre_tool_use.py` HOST_ADAPTERS + `rules/hosts/*.json` + "
        "`.psl/probe/*.json` + 审计链（host_confidence=high 的记录数）。",
        "",
        "| Host | 执法能力（适配器）| 在岗证据（真实流量）| Watch registry | Probe evidence | Chain evidence (0.33.1+) |",
        "|---|---|---|---|---|---|",
    ]
    for h in all_hosts:
        verified = adapters.get(h)
        v_str = "✅" if verified is True else ("❌" if verified is False else "—")
        reg = registry.get(h, {})
        reg_str = str(reg.get("watch_count", 0)) + " paths" if reg else "—"
        pr = probes.get(h, [])
        p_str = "%d file(s)" % len(pr) if pr else "—"
        c = chain.get(h, 0)
        c_str = ("%d rec, last %s" % (c, chain_last.get(h, "?"))) if c else "—"
        # 0.33.1：把两件**不同**的事分成两栏，别用一个 ✅ 盖住两件事。
        #   执法能力 = 钩子被调用时能不能发出三通道 deny（合成输入即可验，`.psl/probe/`）
        #   在岗证据 = 这个宿主**真的会**调用钩子（只能靠真实流量的 host_confidence）
        # 判据：合成探针证明得了前者、证明不了后者；混在一栏就是拿弱证据冒充强证据。
        acting = v_str
        on_duty = "✅ %d rec" % c if c else "— 未验证"
        lines.append("| %s | %s | %s | %s | %s | %s |"
                     % (h, acting, on_duty, reg_str, p_str, c_str))
    lines += ["", "Total: %d hosts" % len(all_hosts)]
    # 0.33.1：verified 标记本身也要可复核。
    # 实测：qoder 的 ✅ 依据 2 条 enforcement_probe 记录，而那 2 条的宿主标签是
    # 0.33.1 之前写的（无 host_confidence 字段）⇒ 它们**证明不了**自己是 qoder
    # ——本项目当时跑在 WorkBuddy 里，标签却是 qoder。这类 ✅ 必须显式挂起，
    # 不许继续当作事实使用。
    suspect = [h for h in all_hosts
               if adapters.get(h) is True and not chain.get(h)]
    if suspect:
        lines += ["", "## ⚠ 「执法能力 ✅、在岗证据缺」的宿主", "",
                  "下面这些宿主**钩子好用**（合成探针能验），但**没有任何 0.33.1 之后的"
                  "高可信链上记录**证明它真的在调用钩子：", ""]
        for h in suspect:
            lines.append("- **%s**：在岗证据 0 条。执法能力可随时用 "
                         "`python tools/enforce_probe.py --host %s` 复核（合成输入，不需要真流量）；"
                         "**在岗证据只能等真流量**，在此之前不得当作「已验证在岗」使用。" % (h, h))
    return "\n".join(lines)


def main():
    out = PKG / "docs" / "HOST_MATRIX.md"
    if "--output" in sys.argv:
        out = Path(sys.argv[sys.argv.index("--output") + 1])
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(build_matrix() + "\n", encoding="utf-8", newline="\n")
    print("host matrix written:", out)


if __name__ == "__main__":
    main()
