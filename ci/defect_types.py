# 判据看守期制（A3，2026-10-15 落地；依据机制论文档 §5 L1 行 / §8-3）
# ══════════════════════════════════════════════════════════════════════
#: 看守期长度（天）。取日期制而非版本制的理由见模块 docstring：
#:   版本计数在本仓机械上不可判定（85 个未推送提交＋研发态版本漂移）。
WATCH_DAYS = 14

#: 复发判据的生效起点 ＝ A3 落地日。只逮此日之后登记的实例 ——
#: 守卫只能抓它存在之后发生的事（grandfathering，与 A1 同构）。
WATCH_ENFORCE_FROM = datetime.date(2026, 10, 15)


def _watch_of(inst):
    """实例的看守期；缺省规则：status=fixed ⇒ 自 date 起 WATCH_DAYS 天。

    可用实例自带 `watch` 字段覆盖：`{"start": "YYYY-MM-DD", "days": N}`。
    日期不可解析 ⇒ None（不猜、不静默按今天处理）。

    ★★ 2026-10-15（A3 落地同日，实测发现的**自相矛盾**：T-06「文档与代码不同锚」）：
      本模块 docstring 明写「复发判据只对 **2026-10-15（A3 落地日）起登记**的实例
      生效 …… 10-12→14 的批次实例是机制落地前的历史工作，与 A1『现有 29 不追溯』
      同一条 grandfathering 纪律」—— 可原实现**只对 B 侧（复发方）**查了门槛
      （`watch_recurrences()` 里的 `d_b < WATCH_ENFORCE_FROM: continue`），
      **A 侧（被看守的实例）无条件建看守期** ⇒ 落地前的历史实例仍被守卫看住，
      与 docstring 说的纪律**不一致**。
      实测后果（本轮 0.50.4 出包收尾）：`PKG16-c` 量具缺陷（T-03）修完登记后，
      与 **10-14 登记的 X-041**（机制落地前）被判「同族复发」⇒ D-31 红。
      而这两条**是两个不同的缺陷**（X-041＝负控锚点绑源码文本形状；本条＝判据把
      两个时刻的读数当同刻比），只是同属 T-03 大类 —— **按大类判复发**会把
      「正常写新判据」误读成「旧判据固化失败」。
      ⇒ 修法：A 侧与 B 侧**同一门槛**（`date >= WATCH_ENFORCE_FROM` 才建看守期）。
        落地当天及以后登记的实例照常进入看守期 —— 守卫只对它存在之后发生的事负责。
      ★ 同时登记的 `watch` 显式覆盖**不受此限**（人工明确要看它，就给它建）。
      ★ 为什么不是「按同一判据」判复发（那样能精确抓靶心）：`guards` 字段里
        一个实例可以指向多条判据（本条 X-050 指 PKG16），且负控/正判据共用前缀
        ⇒ 「同一条判据」在结构上无唯一键可比。门槛修正是**可复算**的最小改动。
    """
    if inst.get("status") != "fixed":
        return None
    w = inst.get("watch") or {}
    start = w.get("start") or inst.get("date")
    try:
        days = int(w.get("days") or WATCH_DAYS)
    except (TypeError, ValueError):
        days = WATCH_DAYS
    try:
        d0 = datetime.date.fromisoformat(str(start))
    except ValueError:
        return None
    # ★ A 侧 grandfathering：落地前登记的历史实例不进看守期（除非显式 watch）。
    #   与 `watch_recurrences()` 的 B 侧门槛**同一口径**（一处纪律两处实现＝T-09）。
    if not w and d0 < WATCH_ENFORCE_FROM:
        return None
    return {"start": d0, "days": days,
            "expiry": d0 + datetime.timedelta(days=days)}


def watch_board(today=None):
    """看守期看板：`[(inst, watch, status)]`，status ∈ {"active", "expired"}。"""
    today = today or datetime.date.today()
    out = []
    for inst in INSTANCES:
        w = _watch_of(inst)
        if not w:
            continue
        out.append((inst, w, "active" if today < w["expiry"] else "expired"))
    return out


def watch_recurrences(today=None):
    """看守期内的同族复发清单 `[(watched_inst, recur_inst), ...]`。

    机械判据：同类型 T 的两实例 A（看守期内）与 B，且
    `B.date > A.watch.start` 且 `B.date >= WATCH_ENFORCE_FROM`。
    ★ 同一天登记不算复发（一次会话修多缺陷的既有形态）；
    ★ 早于 A3 落地日的历史实例不逮（grandfathering）。
    ⇒ 命中即"判据固化失败"：红的是判据，不是产品。
    """
    today = today or datetime.date.today()
    active = [(inst, w) for inst, w, s in watch_board(today) if s == "active"]
    by_id = {i["id"]: i for i in INSTANCES}
    hits = []
    for inst in INSTANCES:
        try:
            d_b = datetime.date.fromisoformat(str(inst.get("date", "")))
        except ValueError:
            continue
        if d_b < WATCH_ENFORCE_FROM:
            continue
        for a_inst, w in active:
            if a_inst["id"] == inst["id"]:
                continue
            if a_inst.get("type") != inst.get("type"):
                continue
            if d_b > w["start"]:
                hits.append((a_inst, inst))
    return hits


def watch_report(today=None):
    """人读看守期看板（--watch）。含在守清单、期满候选、期内复发。"""
    today = today or datetime.date.today()
    board = watch_board(today)
    recur = watch_recurrences(today)
    L = ["判据看守期看板（A3）—— 今天 %s，看守期 %d 天，复发判据生效起点 %s"
         % (today.isoformat(), WATCH_DAYS, WATCH_ENFORCE_FROM.isoformat())]
    L.append("=" * 60)
    act = [(i, w) for i, w, s in board if s == "active"]
    exp = [(i, w) for i, w, s in board if s == "expired"]
    L.append("在守 %d 条（期满日 ＝ start + %d 天）：" % (len(act), WATCH_DAYS))
    for i, w in sorted(act, key=lambda x: x[1]["expiry"]):
        L.append("   %-7s %-6s %s → %s（剩 %d 天）"
                 % (i["id"], i["type"], w["start"].isoformat(),
                    w["expiry"].isoformat(), (w["expiry"] - today).days))
    L.append("期满 %d 条（无复发 ⇒ 可降月度抽样或退役候选）：" % len(exp))
    for i, w in sorted(exp, key=lambda x: x[1]["expiry"]):
        L.append("   %-7s %-6s %s → %s" % (i["id"], i["type"],
                                        w["start"].isoformat(),
                                        w["expiry"].isoformat()))
    L.append("-" * 60)
    if recur:
        L.append("★ 看守期内同族复发 %d 组（判据固化失败 —— 红判据不红产品）："
                 % len(recur))
        for a, b in recur:
            L.append("   %s（%s，%s 起守）⇒ %s（%s，%s 登记）同族"
                     % (a["id"], a["type"], _watch_of(a)["start"].isoformat(),
                        b["id"], b["type"], b.get("date")))
    else:
        L.append("★ 无看守期内同族复发")
    return "\n".join(L)


def coverage(gate_ids=None):
    """返回 (真已守, 声明未兑现, 申报盲区, open 实例列表, 无实例的类型列表)。

    ★★ 2026-10-12 F40 补丁（交接件 §4.6）——**同一份报告两个口径的病**：
      原实现用 `not blind` 计「已守」，那是**声明口径**（结构上配了判据的
      类型数）；而逐行「失守!」用**注册表口径**（判据真在闸门注册表里）。
      表头把「声明了但判据不存在」的 4 类算成已守，与逐行自相矛盾 ——
      F40（口径混装）在登记簿自己身上的复现。
      现在三个数全部按**注册表口径**计，且 真已守＋声明未兑现＋申报盲区
      **恒等于类型总数**（三个数可以用手加出来，可对账）。
    """
    if gate_ids is None:
        gate_ids = gate_ids_from_registry()
    guarded, unfulfilled, blind, opens, no_instance = [], [], [], [], []
    for t, v in TYPES.items():
        if v.get("blind"):
            blind.append(t)
            continue
        gs = v.get("guards") or []
        if not gs:
            # 非 blind 却没配判据 —— check_consistency 会把它判红（有病无药）
            unfulfilled.append(t)
            continue
        missing = [g for g in gs if g not in gate_ids]
        (unfulfilled if missing else guarded).append(t)
    opens = [i for i in INSTANCES if i.get("status") == "open"]
    no_instance = [t for t in TYPES
                   if not any(i.get("type") == t for i in INSTANCES)]
    return guarded, unfulfilled, blind, opens, no_instance


def report(gate_ids=None):
    """人类可读报告（--report）。"""
    if gate_ids is None:
        gate_ids = gate_ids_from_registry()
    guarded, unfulfilled, blind, opens, no_instance = coverage(gate_ids)
    L = []
    L.append("缺陷类型登记簿 —— 覆盖现状")
    L.append("=" * 60)
    # ★ F40 补丁：表头三个数 ＝ 注册表口径，相加 ＝ 类型总数（可对账）
    L.append("类型 %d 类：已守 %d ／ 声明未兑现 %d ／ 申报盲区 %d"
             "（三者相加 ＝ %d）" % (len(TYPES), len(guarded), len(unfulfilled),
                                len(blind), len(TYPES)))
    L.append("实例 %d 条：已闭合 %d ／ 未闭合 %d"
             % (len(INSTANCES), len(INSTANCES) - len(opens), len(opens)))
    L.append("")
    L.append("%-7s %-14s %-8s %s" % ("ID", "名称", "状态", "守护判据"))
    L.append("-" * 60)
    for tid in sorted(TYPES):
        t = TYPES[tid]
        if t.get("blind"):
            st = "盲区"
            gd = "（人工纪律）"
        else:
            missing = [g for g in t.get("guards", []) if g not in gate_ids]
            st = "已守" if not missing else "失守!"
            gd = "、".join(t.get("guards", []))
            if missing:
                gd += " ← 不在注册表: %s" % "、".join(missing)
        L.append("%-7s %-14s %-8s %s" % (tid, t.get("name", "?"), st, gd))
    if no_instance:
        L.append("")
        L.append("▲ 没有实例的类型（还没遇到过，或遇到过没登记）：%s"
                 % "、".join("%s %s" % (t, TYPES[t]["name"]) for t in no_instance))
    if opens:
        L.append("")
        L.append("▲ 未闭合实例（这类错没有被机械守护，或修法未落地）：")
        for i in opens:
            L.append("   %s [%s %s] %s"
                     % (i["id"], i["type"], TYPES[i["type"]]["name"], i["what"]))
            if TYPES[i["type"]].get("discipline"):
                L.append("        人工纪律：%s" % TYPES[i["type"]]["discipline"])
    ok, problems = check_consistency(gate_ids)
    L.append("")
    L.append("-" * 60)
    if ok:
        L.append("★ 登记簿自身一致：每个类型都有人守或已申报盲区")
    else:
        L.append("★ 登记簿有 %d 处不一致：" % len(problems))
        for p in problems:
            L.append("   · %s" % p)
    return "\n".join(L)


def main():
    ap = argparse.ArgumentParser(description="缺陷类型登记簿")
    ap.add_argument("--report", action="store_true", help="人读报告")
    ap.add_argument("--check", action="store_true", help="只跑一致性自检")
    ap.add_argument("--gate-ids", action="store_true",
                    help="打印从闸门注册表提取的判据 ID")
    ap.add_argument("--json", action="store_true", help="机器可读")
    ap.add_argument("--watch", action="store_true",
                    help="看守期看板：在守/期满/期内同族复发（A3）")
    a = ap.parse_args()

    if a.watch:
        print(watch_report())
        return 1 if watch_recurrences() else 0

    ids = gate_ids_from_registry()
    if a.gate_ids:
        print(" ".join(sorted(ids)))
        return 0
    if a.json:
        ok, problems = check_consistency(ids)
        # ★ F40 补丁（同源修改）：--json 与 --report 表头**同一口径**
        #   （注册表口径）。原实现的 "guarded" 用 `not blind` 声明口径计，
        #   与人读报告打架 —— 机器读的口径和人读的口径继续各说各话。
        guarded, unfulfilled, blind, opens, no_instance = coverage(ids)
        print(json.dumps({
            "types": len(TYPES),
            "guarded": len(guarded),
            "declared_unfulfilled": len(unfulfilled),
            "blind": len(blind),
            "instances": len(INSTANCES),
            "open": len(opens),
            "gate_ids": sorted(ids),
            "ok": ok,
            "problems": problems,
        }, ensure_ascii=False, indent=1))
        return 0 if ok else 1
    if a.check:
        ok, problems = check_consistency(ids)
        print("判据 ID（闸门注册表提取）：%s" % ("、".join(sorted(ids)) or "空"))
        if ok:
            print("★ 一致：每个类型都有人守或已申报盲区")
            return 0
        print("★ %d 处不一致：" % len(problems))
        for p in problems:
            print("   · %s" % p)
        return 1
    # 默认：报告
    print(report(ids))
    ok, _ = check_consistency(ids)
    return 0 if ok else 1


