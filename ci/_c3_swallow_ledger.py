"""C3 吞咽登记簿 —— 每个 `except: pass` / `return 默认` 必须写清"它失败时我当什么"。

★★ 为什么要有这份簿（2026-10-22，创始人批准的三步之二）
  容器能坏的方式有限，但**代码把失败咽下去的方式**几乎无限：
  实测 16 个随包模块 428 个 except，其中 163 个把异常吞成"什么都没有"（38%）；
  `host_shield.py` 115 个 except 里 75 个是这种形状。
  "吞掉"本身不一定是错 —— 错的是**没人写下它吞掉之后世界变成什么样**。
  ⇒ 判据 C3：未登记即红；登记了却不存在（死登记）也红。
     两条一起，才逼人每次改动都重新回答一次"这里失败了我当什么"。

★ 键的构造（与 `ci/inbox_guards_0372.py` 的 `_c3_key()` 逐字一致）：
    "<函数名>::<该函数内第几个 except，从 0 起>::<except 类型 + 处理体源码的 sha1 前 6>"
  为什么带哈希：处理体一改，旧键就消失、新键就出现 ⇒ 两边都红 ⇒ 逼人重新登记。
  为什么带序号而不是行号：行号会因上面加一行注释就全漂；序号只在"增删 except"时变，
  而那正是需要重新回答的时刻。

★ 登记的是**决定**，不是豁免。写"接受这个后果"是合法的；
  写"这是 best-effort"而不说失败后世界变成什么样，不算登记（U-25 同一纪律）。

★★ 已知残留（如实写在这里，不许假装闭合）
  ① 本簿当前只覆盖 `SCOPE` 里的模块；其余模块在 `TODO` 里挂账，由 C3 的第二条腿
     （未登记面不许无声扩大）看着。
  ② "吞掉"的判定只认**单条** `pass` / `continue` / `return <默认值>`。
     处理体里有两条语句的（哪怕两条都在掩盖失败）不在本簿范围内 —— 这是判据的
     结构盲区，比"漏登记"更值得记住。
"""

