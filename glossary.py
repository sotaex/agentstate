_DATA_T = re.compile(r'data-t="([^"]+)"')


def unknown(html_text):
    """页面上出现了**未登记**的术语 key ⇒ 返回它们（判据用）。"""
    return [k for k in _DATA_T.findall(html_text or "")
            if k != "__line" and k not in TERMS]


def rendered(html_text):
    """页面上出现的术语 key 列表（判据用）。"""
    return [k for k in _DATA_T.findall(html_text or "") if k != "__line"]
