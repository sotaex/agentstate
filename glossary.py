# ------------------------------------------------------------ 渲染 ----
def _def(key):
    t = TERMS.get(key)
    if not t:
        raise UnknownTerm("术语未登记：%s" % key)
    missing = [f for f in _REQUIRED if not (t.get(f) or "").strip()]
    if missing:
        raise UnknownTerm("术语 %s 定义不完整，缺字段：%s" % (key, "、".join(missing)))
    return t


#: 术语正文里允许的**内联标记**。刻意只放行这两种 —— 定义是我们自己写的、
#: 不是用户输入，放行有限标签即可，换来的是作者能写重点而不用放弃强调。
_ALLOWED_TAGS = ("b", "code")


def render(text):
    """术语正文渲染：**先转义、再放行少量内联标记**。

    ★ 为什么需要它（2026-10-07 实测踩出来的）：
      ① 只做 `_H.escape()` ⇒ 作者写在正文里的 `<b>重点</b>` 会被转义成
         `&lt;b&gt;重点&lt;/b&gt;`，页面上显示成一串标签文本（用户实测截图）；
      ② 什么都不做、直接拼 HTML ⇒ 将来任何一处引号/尖括号写错都会破坏页面结构。
      ⇒ 顺序不能颠倒：**必须先 escape 再还原**，
        否则正文里一个 `&lt;` 会被当成真的标签开符。
    ★ markdown 的 `**…**` 也一并吃掉：作者习惯写它，而页面是 HTML，
      直接吐出去就是满屏星号（这正是创始人截图里看到的东西）。
    ★ 标签白名单之外的 `<…>` 一律保持转义态，不会变成真的标签。
    """
    if not text:
        return ""
    s = _H.escape(text, quote=False)
    s = s.replace("&lt;b&gt;", "<b>").replace("&lt;/b&gt;", "</b>")
    s = s.replace("&lt;code&gt;", "<code>").replace("&lt;/code&gt;", "</code>")
    # ★ markdown 的 `**重点**` ⇒ `<b>重点</b>`（这一步 2026-10-09 补齐）。
    #   为什么现在才补：这句能力在 docstring 里**早就被承诺了**，而实现里
    #   根本没有这一步 —— 词表作者后来索性把正文全改成手写 `<b>`，
    #   于是承诺看起来兑现了。但归因模块（`remediation`）的作者不熟这条约定，
    #   照旧写 `**…**` ⇒ 首页每条失守的"为什么"里**带着星号出现在屏幕上**
    #   （2026-10-09 实测：8 个归因类里有 8 个泄漏）。
    #   ⇒ 与其再强调一遍"别写星号"，不如让渲染真的吃掉它。
    s = re.sub(r"\*\*(.+?)\*\*", r"<b>\1</b>", s)
    # 收尾：清掉任何**没被放行**的成对标签残留之外的裸标签，
    #   `_H.escape` 已把它们变成实体，这里无需再动。
    return s


def chip(key, text=None, mk=False):
    """一个**可点开**的小词条。未登记 ⇒ 抛 `UnknownTerm`（绝不静默）。

    ★ 0.37.1：释义里**不再重复一遍词条名** —— 旧实现是
      `<summary>拦截（L2）</summary><div class="tdef"><b>拦截（L2）</b>：…`，
      点开后同一个词上下各写一遍（纯文本导出、无障碍朗读时会表现为
      「拦截（L2） 拦截（L2）：」，创始人截图三）。
      ⇒ 词已经写在 summary 上，释义直接从正文开始。

    ★★ 0.48.5（交接件 §5.6 乙1）：`mk=True` ＝ **裸「？」芯片** ——
       给「本身是链接、塞不进 details」的词用（筛选条标签、药丸、顶部灯）：
       芯片作**兄弟节点**紧贴链接之后，**不嵌套**（`<a>` 内嵌 interactive
       内容是坏味道）。summary 只放一个「？」；词本名进展开体首行
       （复用上面的 `head` 机制，不另写一套）。
       ★★ 2026-10-13 修（C5）：屏幕上的「？」由 **CSS 的 `::after` 徽章**渲染
       （14×14 圆、10px、写死字号 —— 与「词名＋徽章」形态**同一种形状**）；
       summary 自身的那个字由 `.term.mk>summary{font-size:0}` 隐藏，否则「？？」。
       **不许**把 `::after` 关掉去"消重复" —— 那会让芯片退化成裸文字「？」，
       字号跟着容器漂（药丸 12px／顶部灯 16px），判据 U-16 锁的就是这一条。
    """
    t = _def(key)
    if mk:
        label = "？" if text is None else text
        head = "<b>%s</b>：" % _H.escape(t["w"])     # 本名进展开体首行
        cls = "term mk"
    else:
        label = text or t["w"]
        # ★ 只有当「显示出来的字」与词条本名不同时才补本名：
        #   例：summary 写「最近 24 小时被拉起过」，展开后正文得知道说的谁
        #   （哨兵） —— 否则去掉重复标题的同时把主语也去掉了。
        head = "" if label == t["w"] else "<b>%s</b>：" % _H.escape(t["w"])
        cls = "term"
    # ★ 0.50.4（U-19 互斥小窗，2026-10-15 创始人判定「点开下一个，上一个自动关」）：
    #   `name="term"` ＝ WHATWG HTML **原生互斥手风琴**：同名即同组（不要求
    #   相邻，散在全页也算同组），开一个、浏览器**原生**关掉组里其它 open 的
    #   —— 零 JS、零状态。Edge 120+（2023-12）起支持；旧引擎不认 name ⇒
    #   退回多开（渐进增强，不坏）。病根：`.term>.tdef` 是 fixed 视口定位，
    #   同时开两个就叠两个窗 ⇒ 互斥后同时至多一个，叠压不复存在。
    #   ★ 0.36.1 的 CSS 注释早就写了「点开别的词条会收起上一个」——但那在
    #     HTML 里从未成立（同名 details 从未自动互斥），是把愿望写成了事实；
    #     本属性让这句话第一次成真。
    #   ★ name 放 data-t **之后**：0490 的芯片正则在 data-t 值即停，不受影响；
    #     U-04 ③ 的逐字子串已同步成带 name 的形态（断言强度不变）。
    #   ★ 范围：只锁术语芯片。details.where / item / rem 等**行内**展开不进组
    #     —— 多开无害，互斥反而碍事。
    # ★★ 0.50.6（创始人「能大白话就大白话，用户体验第一」）：**公式标签退场**。
    #   旧形态固定渲染「包含／不含／口径」三行徽章 —— 多数词条的补充信息
    #   只有一条，也照样挂三行标签，用户先读标签再读内容，平白多一跳。
    #   新形态：一句定义 ＋ 按需出现的补充行（无标签，内容自己会说话）。
    #   ★ 五字段写入纪律**不动**（判据 0353 逐词条核齐全、unit 空必须抛错），
    #     变的只是屏幕上显示多少 —— 显示层让步，定义层不松。
    #   ★ 顺序保持 inc→exc→unit：先说"有什么"，再说"不是什么"，最后说"怎么数"。
    sup = "".join('<div class="tsup">%s</div>' % render(t[f])
                  for f in ("inc", "exc", "unit")
                  if (t.get(f) or "").strip())
    # ★★ 0.51.0：代码生成的成品 HTML 块（目前仅拦截词条的规则全表）紧随 inc
    #   之后 —— 不经 render（其白名单只有 b/code），也不带 name（不进互斥组：
    #   外层术语芯片互斥时，用户可能正读到展开的规则表）。
    extra = t.get("list_html") or ""
    if extra:
        sup += extra
    return ("<details class=\"%s\" data-t=\"%s\" name=\"term\"><summary>%s</summary>"
            "<div class=\"tdef\">%s%s%s</div></details>"
            % (cls, _H.escape(key, quote=True), _H.escape(label),
               head, render(t["one"]), sup))


def line(keys, title="这些词是什么意思（点开看）"):
    """一行式术语入口：给**本身是链接**的词用（点不开的地方不硬塞 details）。"""
    body = "".join(
        "<div class=\"trow\" data-t=\"%s\"><b>%s</b> %s%s</div>"
        % (_H.escape(k, quote=True), _H.escape(_def(k)["w"]),
           render(_def(k)["one"]),
           "".join('<div class="tsup">%s</div>' % render(_def(k)[f])
                   for f in ("inc", "exc", "unit")
                   if (_def(k).get(f) or "").strip()))
        for k in keys)
    return ("<details class=\"gloss\" data-t=\"__line\"><summary>%s</summary>"
            "<div class=\"tdef\">%s</div></details>" % (_H.escape(title), body))


