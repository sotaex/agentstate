def _wl(key):
    """态名标题（如「缺粮（Ls）」）。**从 `inbox_model.STATE_LABEL` 派生** ——
    本模块不写第二份态名（判据 `inbox_guards_0372.py` S08 全仓扫第二份声明）。"""
    return "%s（%s）" % (_M.state_short(key), key)


